-- Repo exercises (loaded by the seed task). baseline is how many hidden tests pass on the untouched code; those earn
-- no points. It is measured through run-service (see BaselineChecker) and reset whenever the content changes.
create table repo_exercises (
    id          bigint generated by default as identity primary key,
    slug        varchar(120)    not null unique,
    title       varchar(200)    not null,
    language    varchar(20)     not null,
    difficulty  varchar(10)     not null,
    tags        varchar(500)    not null,
    description varchar(5000)   not null,
    content     varchar(500000) not null,
    sort_order  int             not null,
    baseline    int
);

-- Reviews, skips, Ask AI questions and test runs (FIX). detail is the JSON list of per-test results of a FIX.
-- job_id is the run-service job a FIX was recorded from: unique, so the same result can never be recorded twice.
-- user_id is identity-service's user id; no foreign key, because users live in another service's database.
create table repo_submissions (
    id               bigint generated by default as identity primary key,
    user_id          uuid                     not null,
    repo_exercise_id bigint                   not null references repo_exercises (id) on delete cascade,
    kind             varchar(10)              not null,
    score            int                      not null,
    max_score        int                      not null,
    created_at       timestamp with time zone not null,
    detail           varchar(20000),
    job_id           uuid unique
);

create index idx_repo_submissions_user on repo_submissions (user_id, repo_exercise_id);

-- Runs this service asked run-service for and is waiting to hear about. Written before the run is submitted, so the
-- result event can never arrive first. Only results for jobs listed here are recorded: a user cannot get a score by
-- running code through run-service directly. purpose: FIX (a user's test run) or BASELINE (user_id is null).
create table pending_runs (
    job_id           uuid                     primary key,
    user_id          uuid,
    repo_exercise_id bigint                   not null references repo_exercises (id) on delete cascade,
    purpose          varchar(10)              not null,
    created_at       timestamp with time zone not null
);

create table repo_exercises (
    id          bigint generated by default as identity primary key,
    slug        varchar(120)    not null unique,
    title       varchar(200)    not null,
    language    varchar(20)     not null,
    difficulty  varchar(10)     not null,
    tags        varchar(500)    not null,
    description varchar(5000)   not null,
    content     varchar(500000) not null,
    sort_order  int             not null
);

create table repo_submissions (
    id               bigint generated by default as identity primary key,
    user_id          uuid                     not null,
    repo_exercise_id bigint                   not null references repo_exercises (id) on delete cascade,
    kind             varchar(10)              not null,
    score            int                      not null,
    max_score        int                      not null,
    created_at       timestamp with time zone not null
);

create index idx_repo_submissions_user on repo_submissions (user_id, repo_exercise_id);

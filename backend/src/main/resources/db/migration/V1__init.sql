create table exercises (
    id            bigint generated by default as identity primary key,
    slug          varchar(120)   not null unique,
    title         varchar(200)   not null,
    language      varchar(20)    not null,
    exercise_type varchar(20)    not null,
    difficulty    varchar(10)    not null,
    tags          varchar(500)   not null,
    code          varchar(20000) not null,
    question      varchar(2000)  not null,
    answer        varchar(5000)  not null,
    explanation   varchar(5000)  not null,
    hint          varchar(1000),
    sort_order    int            not null
);

create table attempts (
    id          bigint generated by default as identity primary key,
    user_id     uuid                     not null,
    exercise_id bigint                   not null references exercises (id) on delete cascade,
    answer      varchar(5000),
    correct     boolean                  not null,
    created_at  timestamp with time zone not null
);

create index idx_attempts_user_exercise on attempts (user_id, exercise_id);

create table run_cache (
    hash        varchar(64)              primary key,
    language    varchar(20)              not null,
    status      varchar(20)              not null,
    stdout      varchar(70000)           not null,
    stderr      varchar(70000)           not null,
    exit_code   int                      not null,
    duration_ms bigint                   not null,
    truncated   boolean                  not null,
    created_at  timestamp with time zone not null
);
